// Builds index.html, the full report, from the section files in SECTIONS.
// Each section file is a complete page whose report content sits inside <main>.
// Run `node .report/build.mjs` after editing any section.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SECTIONS = [
  "cover.html",
  "summary.html",
  "01-application.html",
  "02-similar-applications.html",
  "03-milestones.html",
  "04-contributions.html",
  "05-design.html",
  "06-users.html",
  "07-future.html",
  "08-learnings.html",
  "appendices.html",
];

const dir = import.meta.dirname;

const bodies = SECTIONS.map((file) => {
  const html = readFileSync(join(dir, file), "utf8");
  const match = html.match(/<main>([\s\S]*?)<\/main>/);
  if (!match) throw new Error(`${file} has no <main> element.`);
  return match[1].trim();
});

// The contents list holds every h1 and h2 that carries an id, in report order.
const chapters = [];
for (const [index, body] of bodies.entries()) {
  for (const [, level, id, text] of body.matchAll(/<h([12]) id="([^"]+)">([\s\S]*?)<\/h\1>/g)) {
    if (level === "1") {
      chapters.push({ id, text, children: [] });
    } else if (chapters.length === 0) {
      throw new Error(`${SECTIONS[index]} has an h2 before any h1 with an id.`);
    } else {
      chapters.at(-1).children.push({ id, text });
    }
  }
}

const toc = chapters
  .map(({ id, text, children }) => {
    const sub = children.length
      ? `\n          <ul>\n${children.map((c) => `            <li><a href="#${c.id}">${c.text}</a></li>`).join("\n")}\n          </ul>\n        `
      : "";
    return `        <li><a href="#${id}">${text}</a>${sub}</li>`;
  })
  .join("\n");

const [cover, ...rest] = bodies;

const page = `<!doctype html>
<!-- Generated by build.mjs from the section files. Edit those files and rebuild, rather than editing this one. -->
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>aisus final report</title>
    <link rel="stylesheet" href="style.css">
  </head>
  <body>
    <main>
${cover}

      <section class="report-section toc">
        <h1>Contents</h1>
        <ul>
${toc}
        </ul>
      </section>

${rest.join("\n\n")}
    </main>
  </body>
</html>
`;

writeFileSync(join(dir, "index.html"), page);
console.log(`Wrote index.html from ${SECTIONS.length} sections.`);
