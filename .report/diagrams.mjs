// Draws the report's design figures with the aisus viewer.
//
//   node .report/diagrams.mjs [--check] [<name> ...]
//
// Each <name> is a map in .report/diagrams/<name>.json, and every map there is drawn when no name
// is given. A map is checked as the aisus validator checks a draft: the schema, the semantic checks
// and every citation against this repository. With --check the script stops after the checks.
// Otherwise it bundles engine/viewer.js into engine/aisus-viewer.js, writes a live figure page
// figures/design/<name>.html whose boxes open their cited lines on GitHub, and saves the drawn map
// from that page in headless Chromium as figures/design/<name>.svg for the report to embed.

import * as esbuild from "esbuild";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { pathToFileURL } from "node:url";
import { layoutWorkerDefine } from "../esbuild.mjs";

const report = import.meta.dirname;
const root = join(report, "..");
const mapsDir = join(report, "diagrams");
const engineDir = join(report, "engine");
const figuresDir = join(report, "figures/design");
const scratch = join(root, "out/report");

/** The size of the window each map is laid out and drawn in, which is the report's text column. */
const VIEWPORT = { width: 748, height: 560 };
/**
 * A wide, short window for the figures in WIDE_FIGURES. The layout runs both directions and keeps
 * the one that fits its window better, so in this window a chain of boxes runs left to right.
 */
const WIDE_VIEWPORT = { width: 1600, height: 400 };
const WIDE_FIGURES = new Set(["map-format"]);
/** How long a figure page may take to draw its map. */
const DRAW_TIMEOUT_MS = 20_000;

/** The validator's checks and the page's JSON escaping, bundled for Node from the core model. */
async function loadModel() {
  const outfile = join(scratch, "model.mjs");
  await esbuild.build({
    absWorkingDir: root,
    stdin: {
      contents: [
        'export { checkSubmission } from "@aisus/core/model/submission";',
        'export { checkCitations } from "@aisus/core/model/citations";',
        'export { collectGitFacts, repositoryFromGit } from "@aisus/core/model/git";',
        'export { escapeJson } from "@aisus/core/model/page";',
      ].join("\n"),
      resolveDir: root,
      loader: "js",
    },
    bundle: true,
    outfile,
    platform: "node",
    format: "esm",
    target: "node22",
    logLevel: "warning",
  });
  return import(pathToFileURL(outfile).href);
}

/** The engine for figure pages: the viewer with its layout worker, and the viewer's stylesheet. */
async function buildEngine() {
  await esbuild.build({
    absWorkingDir: root,
    entryPoints: [join(engineDir, "viewer.js")],
    outfile: join(engineDir, "aisus-viewer.js"),
    bundle: true,
    platform: "browser",
    format: "iife",
    target: "es2022",
    minify: true,
    legalComments: "inline",
    logLevel: "warning",
    define: await layoutWorkerDefine(),
  });
  writeFileSync(join(engineDir, "aisus-viewer.css"), readFileSync(join(root, "packages/viewer/styles.css"), "utf8"));
}

function escapeHtml(text) {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

/**
 * `svg` with each CSS `color(srgb r g b / a)`, which the viewer's computed styles give for mixed
 * colours, written as `rgba()`, which every SVG reader draws.
 */
function plainColors(svg) {
  return svg.replace(/color\(srgb ([\d.e-]+) ([\d.e-]+) ([\d.e-]+)(?: \/ ([\d.e-]+))?\)/g, (_, r, g, b, a = "1") => {
    const channel = (value) => Math.round(Math.min(1, Math.max(0, Number(value))) * 255);
    return `rgba(${channel(r)}, ${channel(g)}, ${channel(b)}, ${Number(a)})`;
  });
}

function figurePage(title, data, escapeJson) {
  const engine = relative(figuresDir, engineDir).split("\\").join("/");
  return `<!doctype html>
<!-- Generated by .report/diagrams.mjs from .report/diagrams/. Edit the map and rerun the script, rather than editing this page. -->
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>${escapeHtml(title)}</title>
    <link rel="stylesheet" href="${engine}/aisus-viewer.css">
  </head>
  <body>
    <script type="application/json" id="aisus-data">${escapeJson(JSON.stringify(data))}</script>
    <script src="${engine}/aisus-viewer.js"></script>
  </body>
</html>
`;
}

/** Opens each figure page in headless Chromium and saves its drawn map as an SVG beside it. */
async function saveImages(names) {
  const { chromium } = await import("playwright");
  const browser = await chromium.launch();
  try {
    for (const name of names) {
      const viewport = WIDE_FIGURES.has(name) ? WIDE_VIEWPORT : VIEWPORT;
      const page = await browser.newPage({ viewport, colorScheme: "light" });
      const errors = [];
      page.on("pageerror", (error) => errors.push(error.message));
      await page.goto(pathToFileURL(join(figuresDir, `${name}.html`)).href);
      const svg = await page.evaluate(async (timeout) => {
        const end = Date.now() + timeout;
        while (Date.now() < end) {
          const image = window.aisus === undefined ? null : await window.aisus.image("svg");
          if (image !== null) return image;
          await new Promise((resolve) => setTimeout(resolve, 100));
        }
        return null;
      }, DRAW_TIMEOUT_MS);
      await page.close();
      if (svg === null) throw new Error(`${name}: the figure page drew nothing${errors.length > 0 ? `: ${errors.join("; ")}` : ""}`);
      writeFileSync(join(figuresDir, `${name}.svg`), plainColors(svg));
      console.log(`Wrote ${relative(root, join(figuresDir, `${name}.svg`))}`);
    }
  } finally {
    await browser.close();
  }
}

async function main(args) {
  const checkOnly = args.includes("--check");
  const named = args.filter((arg) => arg !== "--check");
  const names = named.length > 0 ? named : readdirSync(mapsDir).filter((file) => file.endsWith(".json")).map((file) => file.slice(0, -".json".length)).sort();
  const model = await loadModel();
  const facts = model.collectGitFacts(root);
  const repository = facts === null ? null : model.repositoryFromGit(facts);

  const candidates = new Map();
  let failed = false;
  for (const name of names) {
    let doc;
    try {
      doc = JSON.parse(readFileSync(join(mapsDir, `${name}.json`), "utf8"));
    } catch (error) {
      console.error(`${name}: cannot read the map: ${error.message}`);
      failed = true;
      continue;
    }
    const kind = doc?.diagram_type === "sequence" ? "sequence" : "architecture";
    const { removed, errors } = model.checkSubmission(doc, { output: `figures/design/${name}.html`, repository, kind }, (map) => model.checkCitations(map, root));
    for (const pointer of removed) console.warn(`${name}: removed ${pointer}, which the viewer sets itself`);
    for (const issue of errors) console.error(`${name}: ${issue.code} at ${issue.pointer || "/"}: ${issue.message}`);
    if (errors.length > 0) failed = true;
    else {
      candidates.set(name, doc);
      console.log(`${name}: valid`);
    }
  }
  if (failed) return 1;
  if (checkOnly) return 0;

  await buildEngine();
  mkdirSync(figuresDir, { recursive: true });
  for (const [name, doc] of candidates) {
    const title = doc.meta.title;
    writeFileSync(join(figuresDir, `${name}.html`), figurePage(title, { title, doc, repository }, model.escapeJson));
  }
  await saveImages([...candidates.keys()]);
  return 0;
}

process.exitCode = await main(process.argv.slice(2));
